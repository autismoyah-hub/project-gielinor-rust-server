//! Opt-in C-008 wire fixture, not gameplay or an account/world-state mutation.
//! A real child view has stock terrain and its own NPC stream. No synthetic root scenery.
use gielinor_protocol::{
    buffer::{BitWriter, DecodeError},
    framing::Packet,
    npc_sync,
};
use gielinor_world::CoordGrid;

pub const CHILD_ID: u16 = 1;
pub const NPC_INDEX: u16 = 30000;
pub const DIMENSIONS: [u16; 2] = [16, 16];
pub const ANCHOR: [i32; 2] = [10423 * 128 + 64, 110 * 128 + 64];
pub const ANGLE: u16 = 512;
pub const NPC_TILE: [u16; 2] = [10, 8];

#[derive(Clone, Default)]
pub struct Observer {
    base: Option<CoordGrid>,
    npcs: npc_sync::State,
}
pub struct Frame {
    pub root_entities: Packet,
    pub child_packets: Vec<Packet>,
}
fn active_child() -> Packet {
    Packet {
        opcode: 47,
        payload: vec![0, CHILD_ID as u8, 0],
    }
}
fn spawn(base: CoordGrid) -> Result<Packet, DecodeError> {
    let x = i16::try_from(ANCHOR[0] - base.x() * 128)
        .map_err(|_| DecodeError::InvalidValue("fixture X"))?;
    let z = i16::try_from(ANCHOR[1] - base.z() * 128)
        .map_err(|_| DecodeError::InvalidValue("fixture Z"))?;
    // count0; ID1; mask0; negated2x2 zones; owner0+128; config-1 LE;
    // signed16 deltas X/Z/angle, no Y delta (format 0b10_10_00_10).
    let mut payload = vec![0, 0, 1, 0, 0u8.wrapping_sub(0x22), 128, 255, 255, 0xa2];
    payload.extend(x.to_be_bytes());
    payload.extend(z.to_be_bytes());
    payload.extend(ANGLE.to_be_bytes());
    Ok(Packet {
        opcode: 122,
        payload,
    })
}
fn rebuild() -> Result<Packet, DecodeError> {
    let mut bits = BitWriter::default();
    for level in 0..4 {
        for x in 0..2u32 {
            for z in 0..2u32 {
                bits.write(1, u32::from(level == 0))?;
                if level == 0 {
                    bits.write(26, ((400 + x) << 14) | ((400 + z) << 3))?;
                }
            }
        }
    }
    // Base0,0, one distinct source map square (50,50 =>12850); no XTEA tail in V4.
    let mut payload = vec![0, 0, 0, 0, 0, 1];
    payload.extend(bits.into_bytes());
    Ok(Packet {
        opcode: 109,
        payload,
    })
}
impl Observer {
    pub fn cycle(&mut self, base: CoordGrid, npc_type: u16) -> Result<Frame, DecodeError> {
        if base.level() != 0 || self.base.is_some_and(|old| old != base) {
            return Err(DecodeError::InvalidValue(
                "C008 fixture requires unchanged root build area",
            ));
        }
        let initial = self.base.is_none();
        let root_entities = if initial {
            spawn(base)?
        } else {
            Packet {
                opcode: 122,
                payload: vec![1, 1, 0],
            }
        };
        let mut packets = vec![active_child()];
        if initial {
            packets.push(rebuild()?);
        }
        packets.push(gielinor_protocol::world_context::empty_entities());
        packets.push(gielinor_protocol::world_context::npc_origin(8, 8));
        let npc = npc_sync::Npc {
            index: NPC_INDEX,
            generation: 1,
            type_id: npc_type,
            position: npc_sync::Position {
                x: NPC_TILE[0],
                z: NPC_TILE[1],
                level: 0,
            },
            visible: true,
            teleport: false,
            jump: false,
            direction: 6,
            spawn_cycle: None,
            movement: npc_sync::Movement::None,
            extended: &[],
            initial_extended: &[],
        };
        let payload = self.npcs.encode(
            npc_sync::Position {
                x: 8,
                z: 8,
                level: 0,
            },
            false,
            &[npc],
            1,
        )?;
        packets.push(Packet {
            opcode: 85,
            payload,
        });
        packets.push(gielinor_protocol::world_context::active_root(0)?);
        self.base = Some(base);
        Ok(Frame {
            root_entities,
            child_packets: packets,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn base() -> CoordGrid {
        CoordGrid::new(10368, 56, 0).unwrap()
    }
    #[test]
    fn matches_original_239_nonempty_admission_retention_and_rebuild() {
        // Generated by the original RSProt239 control for this synthetic fixture.
        // These are packet controls, not copied cache/source assets.
        let oracle = [
            ("active", "000100"),
            ("rebuild", "0000000000018c8190119032223226404644c88000"),
            ("spawn", "00000100de80ffffa21bc01b400200"),
            ("retain", "010100"),
        ];
        for (name, packet) in [
            ("active", active_child()),
            ("spawn", spawn(base()).unwrap()),
            (
                "retain",
                Packet {
                    opcode: 122,
                    payload: vec![1, 1, 0],
                },
            ),
            ("rebuild", rebuild().unwrap()),
        ] {
            let expected = oracle.iter().find(|(key, _)| *key == name).unwrap().1;
            let actual: String = packet.payload.iter().map(|b| format!("{b:02x}")).collect();
            assert_eq!(actual, expected, "{name}");
        }
    }
    #[test]
    fn child_context_and_actor_survive_repeated_cycles_independently_per_session() {
        let mut a = Observer::default();
        let mut b = Observer::default();
        let first = a.cycle(base(), 1).unwrap();
        let peer = b.cycle(base(), 1).unwrap();
        assert_eq!(first.root_entities.payload, peer.root_entities.payload);
        assert_eq!(
            first
                .child_packets
                .iter()
                .map(|p| p.opcode)
                .collect::<Vec<_>>(),
            [47, 109, 122, 116, 85, 47]
        );
        assert_eq!(first.child_packets[4].payload[0], 0); // first child NPC admission
        for _ in 0..50 {
            let next = a.cycle(base(), 1).unwrap();
            assert_eq!(next.root_entities.payload, [1, 1, 0]);
            assert_eq!(
                next.child_packets
                    .iter()
                    .map(|p| p.opcode)
                    .collect::<Vec<_>>(),
                [47, 122, 116, 85, 47]
            );
            assert_eq!(next.child_packets[3].payload[0], 1); // one retained NPC
            assert_eq!(next.child_packets.last().unwrap().payload, [0, 0, 0]);
        }
        assert!(a.cycle(CoordGrid::new(10376, 56, 0).unwrap(), 1).is_err());
    }
    #[test]
    fn invalid_origin_or_actor_is_rejected_before_admission() {
        assert!(Observer::default()
            .cycle(CoordGrid::new(10368, 56, 1).unwrap(), 1)
            .is_err());
        assert!(Observer::default().cycle(base(), 16384).is_err());
        assert!(Observer::default()
            .cycle(CoordGrid::new(0, 0, 0).unwrap(), 1)
            .is_err());
    }
}
